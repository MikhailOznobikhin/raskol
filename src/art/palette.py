def hx(s: str) -> tuple[int, int, int, int]:
    s = s.lstrip("#")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16), 255)


def mix(a, b, t: float):
    """Смешать два цвета (можно кортежи или hex)."""
    if isinstance(a, str):
        a = hx(a)
    if isinstance(b, str):
        b = hx(b)
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(4))


def ramp(colors, t: float):
    """Взять точку на рампе 0..1 с линейной интерполяцией (без сглаживания
    по палитре — специально, чтобы получать промежуточные тона)."""
    t = max(0.0, min(1.0, t))
    n = len(colors) - 1
    pos = t * n
    i = min(int(pos), n - 1)
    f = pos - i
    return mix(colors[i], colors[i + 1], f)


def shade(color, amount: float):
    """Осветлить (>0) или затемнить (<0) цвет в сторону тёплого/холодного."""
    c = hx(color) if isinstance(color, str) else color
    if amount >= 0:
        return mix(c, (255, 244, 214, 255), amount)
    return mix(c, (6, 8, 12, 255), -amount)
